def sorted_files(path: Path) -> Iterable[Path]:
    return sorted((item for item in path.rglob("*") if item.is_file() and "__pycache__" not in item.parts and item.suffix != ".pyc"), key=lambda item: item.as_posix())


def source_relative(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def banner(source: str, suffix: str, data: bytes) -> bytes:
    message = (
        f"GENERATED by tools/generate-plugins.py from {source} — kit v{KIT_VERSION}. "
        "Do not edit; edit the canonical source."
    ).encode("utf-8")
    if suffix == ".md":
        comment = b"<!-- " + message + b" -->\n"
        if data.startswith(b"---"):
            if not data.startswith(b"---\n"):
                raise ValueError(f"frontmatter in {source} does not start with a standalone --- delimiter")
            closing = data.find(b"\n---\n", 4)
            if closing < 0:
                raise ValueError(f"frontmatter in {source} has no closing --- delimiter")
            frontmatter_end = closing + len(b"\n---\n")
            rendered = data[:frontmatter_end] + b"\n" + comment + data[frontmatter_end:]
            assert rendered.startswith(b"---"), f"frontmatter moved away from byte zero in {source}"
            return rendered
        return comment + b"\n" + data
    if suffix in {".py", ".sh"}:
        prefix = b"# " + message + b"\n\n"
        if data.startswith(b"#!"):
            shebang, newline, rest = data.partition(b"\n")
            return shebang + newline + prefix + rest
        return prefix + data
    return data


def is_verbatim_copy(source: str) -> bool:
    return any(source == root or source.startswith(f"{root}/") for root in VERBATIM_COPY_ROOTS)


def copy_file(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    relative = source_relative(source)
    data = source.read_bytes()
    rendered = data if is_verbatim_copy(relative) else banner(relative, source.suffix, data)
    destination.write_bytes(rendered)
    destination.chmod(stat.S_IMODE(source.stat().st_mode))


def copy_tree(source: Path, destination: Path) -> None:
    for file_path in sorted_files(source):
        copy_file(file_path, destination / file_path.relative_to(source))


ICON_SIZE = 1024
ICON_LEVELS = 8
ICON_BACKGROUND = (0x1F, 0x4F, 0xBF)
ICON_FOREGROUND = (0xFF, 0xFF, 0xFF)
# A paper airplane flying up and to the right: the upper wing and the body,
# separated by a fold that narrows to the nose.
ICON_TRIANGLES = (
    ((812.0, 212.0), (196.0, 468.0), (470.0, 560.0)),
    ((812.0, 212.0), (488.0, 584.0), (560.0, 812.0)),
)


def _icon_edges(triangle):
    """Half-planes a*x + b*y + c >= 0 (unit normals) whose intersection is the triangle."""
    (x0, y0), (x1, y1), (x2, y2) = triangle
    orientation = (x1 - x0) * (y2 - y0) - (y1 - y0) * (x2 - x0)
    edges = []
    for (ax, ay), (bx, by) in (((x0, y0), (x1, y1)), ((x1, y1), (x2, y2)), ((x2, y2), (x0, y0))):
        a, b = ay - by, bx - ax
        if orientation < 0:
            a, b = -a, -b
        length = (a * a + b * b) ** 0.5
        a, b = a / length, b / length
        edges.append((a, b, -(a * ax + b * ay)))
    return edges


def _icon_coverage_row(edges, yc, row):
    """Raise row[x] to this triangle's coverage of pixel x, for one pixel row centred at yc."""
    lo_outer, hi_outer, lo_inner, hi_inner = 0.0, float(ICON_SIZE), 0.0, float(ICON_SIZE)
    for a, b, c in edges:
        k = b * yc + c
        for threshold, inner in ((-0.5, False), (0.5, True)):
            if a > 0:
                bound = (threshold - k) / a
                if inner:
                    lo_inner = max(lo_inner, bound)
                else:
                    lo_outer = max(lo_outer, bound)
            elif a < 0:
                bound = (threshold - k) / a
                if inner:
                    hi_inner = min(hi_inner, bound)
                else:
                    hi_outer = min(hi_outer, bound)
            elif k < threshold:
                if inner:
                    lo_inner, hi_inner = 1.0, 0.0
                else:
                    return
    start = max(0, int(lo_outer - 0.5))
    stop = min(ICON_SIZE, int(hi_outer + 0.5) + 1)
    for x in range(start, stop):
        xc = x + 0.5
        if lo_inner <= xc <= hi_inner:
            coverage = 1.0
        else:
            coverage = min(a * xc + b * yc + c for a, b, c in edges) + 0.5
            coverage = max(0.0, min(1.0, coverage))
        level = int(coverage * ICON_LEVELS + 0.5)
        if level > row[x]:
            row[x] = level


def _png_chunk(kind: bytes, data: bytes) -> bytes:
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)


def _stored_zlib(data: bytes) -> bytes:
    """A zlib stream of stored deflate blocks only, so no compressor implementation shapes the bytes."""
    out = bytearray(b"\x78\x01")
    position = 0
    while True:
        block = data[position:position + 0xFFFF]
        position += len(block)
        final = position >= len(data)
        out += bytes([1 if final else 0]) + struct.pack("<HH", len(block), len(block) ^ 0xFFFF) + block
        if final:
            break
    out += struct.pack(">I", zlib.adler32(data) & 0xFFFFFFFF)
    return bytes(out)


def render_icon_png() -> bytes:
    """The kit's plugin icon: a 1024 px, palette PNG of a paper airplane, byte-identical on every run."""
    palette = bytearray()
    for level in range(ICON_LEVELS + 1):
        for back, fore in zip(ICON_BACKGROUND, ICON_FOREGROUND):
            palette.append(back + ((fore - back) * level + ICON_LEVELS // 2) // ICON_LEVELS)
    edge_sets = [_icon_edges(triangle) for triangle in ICON_TRIANGLES]
    raw = bytearray()
    for y in range(ICON_SIZE):
        row = bytearray(ICON_SIZE)
        for edges in edge_sets:
            _icon_coverage_row(edges, y + 0.5, row)
        raw += b"\x00" + row
    header = struct.pack(">IIBBBBB", ICON_SIZE, ICON_SIZE, 8, 3, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _png_chunk(b"IHDR", header)
        + _png_chunk(b"PLTE", bytes(palette))
        + _png_chunk(b"IDAT", _stored_zlib(bytes(raw)))
        + _png_chunk(b"IEND", b"")
    )



def write_icon(destination: Path, output: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(render_icon_png())
    destination.chmod(0o644)
    GENERATED_SOURCES[destination.relative_to(output).as_posix()] = "tools/generate-plugins.py"


def write_plugin_manifest(plugin: str, data: dict[str, object], destination: Path) -> None:
    payload = {
        "author": {"name": "Jack Li"},
        "description": data["description"],
        "keywords": list(data["keywords"]),
        "license": "Apache-2.0",
        "name": plugin,
        "version": KIT_VERSION,
    }
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    destination.chmod(0o644)


def write_provenance(output: Path) -> None:
    entries = []
    for generated in sorted_files(output):
        relative_path = generated.relative_to(output).as_posix()
        if relative_path == MANIFEST_PATH:
            continue
        entries.append(
            {
                "path": relative_path,
                "source": "tools/generate-plugins.py"
                if relative_path.endswith("/.claude-plugin/plugin.json")
                else generated_source(output, generated),
                "sha256": hashlib.sha256(generated.read_bytes()).hexdigest(),
                "kit_version": KIT_VERSION,
            }
        )
    manifest = output / MANIFEST_PATH
    manifest.write_text(
        json.dumps(sorted(entries, key=lambda entry: entry["path"]), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    manifest.chmod(0o644)


def generated_source(output: Path, generated: Path) -> str:
    """Read the canonical source recorded while populating the output tree."""
    return GENERATED_SOURCES[generated.relative_to(output).as_posix()]


GENERATED_SOURCES: dict[str, str] = {}


def materialize_variants(check_only: bool) -> int:
    if not PREAMBLE_PATH.is_file():
        raise ValueError("variant preamble is missing: skills/variants/subordination-preamble.md")
    preamble = PREAMBLE_PATH.read_bytes()
    if not preamble.endswith(b"\n") or preamble.endswith(b"\n\n"):
        raise ValueError("variant preamble must end with exactly one newline")

    differences = []
    for skill in VARIANT_SKILLS:
        base_path = ROOT / "skills" / skill / "SKILL.md"
        base = base_path.read_bytes()
        if not base.startswith(b"---\n"):
            raise ValueError(f"variant base does not start with frontmatter: {source_relative(base_path)}")
        delimiter = b"\n---\n"
        delimiter_index = base.find(delimiter, len(b"---\n"))
        if delimiter_index < 0:
            raise ValueError(f"variant base has no closing frontmatter: {source_relative(base_path)}")
        frontmatter_end = delimiter_index + len(delimiter)
        expected = base[:frontmatter_end] + b"\n" + preamble + b"\n" + base[frontmatter_end:]
        derived_path = VARIANTS_ROOT / skill / "SKILL.md"
        if check_only:
            if not derived_path.is_file():
                differences.append(f"missing: {source_relative(derived_path)}")
            elif derived_path.read_bytes() != expected:
                differences.append(f"different: {source_relative(derived_path)}")
        else:
            derived_path.parent.mkdir(parents=True, exist_ok=True)
            derived_path.write_bytes(expected)
            derived_path.chmod(stat.S_IMODE(base_path.stat().st_mode))

    if differences:
        print("variant derivation drift:", file=sys.stderr)
        print("\n".join(differences), file=sys.stderr)
        return 1
    return 0


def record_copy(source: Path, destination: Path, output: Path) -> None:
    copy_file(source, destination)
    GENERATED_SOURCES[destination.relative_to(output).as_posix()] = source_relative(source)


def record_tree(source: Path, destination: Path, output: Path) -> None:
    for file_path in sorted_files(source):
        record_copy(file_path, destination / file_path.relative_to(source), output)


def generate_tree(output: Path) -> None:
    GENERATED_SOURCES.clear()
    for plugin, data in sorted(PLUGINS.items()):
        plugin_root = output / plugin
        skills = tuple(data["skills"])
        for skill in sorted(skills):
            source = (
                VARIANTS_ROOT / skill
                if plugin in VARIANT_PLUGINS and skill in VARIANT_SKILLS
                else ROOT / "skills" / skill
            )
            record_tree(source, plugin_root / "skills" / skill, output)
        for shared_asset, receiving_skills in sorted(SHARED_MAP.items()):
            for skill in sorted(set(skills) & set(receiving_skills)):
                record_copy(
                    ROOT / "shared" / shared_asset,
                    plugin_root / "skills" / skill / shared_asset,
                    output,
                )
        for tool in sorted(TOOLS_SET):
            source = ROOT / "tools" / tool
            destination = plugin_root / "tools" / tool
            if source.is_dir():
                record_tree(source, destination, output)
            else:
                record_copy(source, destination, output)
        record_copy(HOOKS_SOURCE, plugin_root / "hooks" / "hooks.json", output)
        record_copy(MONITORS_SOURCE, plugin_root / "monitors" / "monitors.json", output)
        for engine_member in ENGINE_SET:
            record_copy(ROOT / "tools" / engine_member,
                        plugin_root / "tools" / engine_member, output)
        record_tree(ROOT / "vendor", plugin_root / "vendor", output)
        record_copy(ROOT / "LICENSE", plugin_root / "LICENSE", output)
        record_tree(ROOT / "LICENSES", plugin_root / "LICENSES", output)
        manifest = plugin_root / ".claude-plugin" / "plugin.json"
        write_plugin_manifest(plugin, data, manifest)
        write_icon(plugin_root / ".claude-plugin" / "icon.png", output)
    write_provenance(output)


def file_map(root: Path) -> dict[str, tuple[str, int, bytes]]:
    if not root.exists():
        return {}
    files = {}
    for path in sorted(root.rglob("*")):
        status = path.lstat()
        if stat.S_ISDIR(status.st_mode):
            continue
        relative = path.relative_to(root).as_posix()
        mode = stat.S_IMODE(status.st_mode)
        if stat.S_ISREG(status.st_mode):
            files[relative] = ("regular", mode, path.read_bytes())
        else:
            files[relative] = ("non-regular", mode, b"")
    return files


def check_tree(expected: Path, actual: Path) -> int:
    expected_files = file_map(expected)
    actual_files = file_map(actual)
    paths = sorted(set(expected_files) | set(actual_files))
    differences = []
    for path in paths:
        if path not in actual_files:
            differences.append(f"missing: {path}")
        elif path not in expected_files:
            differences.append(f"extra: {path}")
        elif expected_files[path] != actual_files[path]:
            differences.append(f"different: {path}")
    if differences:
        print("plugin generation drift:", file=sys.stderr)
        print("\n".join(differences), file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when plugins/ has generation drift")
    arguments = parser.parse_args()
    if materialize_variants(arguments.check):
        return 1
    with tempfile.TemporaryDirectory(prefix="agentic-dev-team-skills-plugins-") as temporary:
        staging = Path(temporary) / "plugins"
        staging.mkdir()
        generate_tree(staging)
        if arguments.check:
            return check_tree(staging, OUTPUT_ROOT)
        if OUTPUT_ROOT.exists():
            shutil.rmtree(OUTPUT_ROOT)
        shutil.move(str(staging), str(OUTPUT_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
