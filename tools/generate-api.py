TOOLS_DIR = Path(__file__).resolve().parent
GENERATED_PREFIX = 'tools/relay_engine/generated/api/'


def build_registry():
    return api_protocol.discovery_registry()


def generate(tools_dir: Path) -> dict[str, bytes]:
    # The root selects destinations only; it never contributes to schema bytes.
    registry = build_registry()
    artifact = api_schema.export_schema(registry, api_definitions.PROTOCOL)
    bindings = {'api_3_0.rs': emit_rust(registry, artifact),
                'api_3_0.ts': emit_typescript(registry, artifact)}
    hashes = {name: hashlib.sha256(body).hexdigest() for name, body in bindings.items()}
    return {GENERATED_PREFIX + name: body for name, body in
            dict(bindings, **{'schema-3.0.json': artifact.canonical_bytes,
                             'manifest.json': build_manifest(artifact, hashes, tuple(registry.operations))}).items()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--write', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    differing = []
    for name, body in sorted(generate(TOOLS_DIR).items()):
        if not name.startswith(GENERATED_PREFIX) or Path(name).name != name[len(GENERATED_PREFIX):]:
            raise ValueError('invalid_generated_destination')
        path = TOOLS_DIR.parent / name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
        elif not path.is_file() or path.read_bytes() != body:
            differing.append(name)
    for name in differing:
        print(name)
    return int(bool(differing))



def build_manifest(artifact: api_schema.SchemaArtifact, binding_hashes, operations) -> bytes:
    return api_schema.jcs.jcs_encode({'protocol': artifact.protocol,
        'schema_digest': artifact.digest, 'schema_byte_count': str(artifact.byte_count),
        'bindings': dict(binding_hashes), 'operations': list(operations)})


def _quoted(value):
    return json.dumps(value, ensure_ascii=True)


def _rust_regex(pattern):
    def sequence(tokens):
        pieces = []
        for kind, value in tokens:
            name = str(kind)
            if name == 'LITERAL':
                pieces.append(f'Rx::Class(false, vec![({value}, {value})])')
            elif name == 'NOT_LITERAL':
                pieces.append(f'Rx::Class(true, vec![({value}, {value})])')
            elif name == 'IN':
                negate = bool(value and str(value[0][0]) == 'NEGATE')
                ranges = []
                for tag, item in value[int(negate):]:
                    if str(tag) == 'LITERAL':
                        ranges.append((item, item))
                    elif str(tag) == 'RANGE':
                        ranges.append(item)
                    else:
                        raise ValueError('unsupported_regex_class')
                pieces.append('Rx::Class(' + str(negate).lower() + ', vec![' + ','.join(f'({a},{b})' for a, b in ranges) + '])')
            elif name == 'SUBPATTERN':
                if value[1:3] != (0, 0):
                    raise ValueError('unsupported_regex_flags')
                pieces.append(sequence(value[3]))
            elif name == 'BRANCH':
                pieces.append('Rx::Alt(vec![' + ','.join(sequence(branch) for branch in value[1]) + '])')
            elif name == 'MAX_REPEAT':
                minimum, maximum, child = value
                bound = 'usize::MAX' if str(maximum) == 'MAXREPEAT' else str(maximum)
                pieces.append(f'Rx::Repeat({minimum}, {bound}, Box::new({sequence(child)}))')
            else:
                raise ValueError('unsupported_regex')
        return 'Rx::Seq(vec![' + ','.join(pieces) + '])'
    return sequence(regex_parser.parse(pattern, 0))


